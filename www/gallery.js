// A picture as a board (board.js).
export function pictureBoard(picture) {
    const board = emptyBoard();
    picture.rows.forEach((row, y) => {
        [...row].forEach((point, x) => {
            board[y*gridsize + x] = point == 'X' ? black : point == 'O' ? white : 0;
        });
    });
    return board;
}

// The pictures in a new order: a fresh shuffle each time the page opens.
export function shuffledPictures(random = Math.random) {
    const order = [...pictures];
    for (let i = order.length - 1; i > 0; --i) {
        const j = Math.floor(random()*(i + 1));
        [order[i], order[j]] = [order[j], order[i]];
    }
    return order;
}
